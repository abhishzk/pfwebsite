<SlideOver bind:open kicker="Container loading concept" title="Engineering note">
	<p class="lede">
		The prototypes are a working model of the decision, not a vision system. Real shipment totals go
		in; pallet heights, camera readings and outcomes are generated by rules on the page, labelled as
		simulated everywhere they appear.
	</p>

	<h3>How it is built</h3>
	<ul>
		<li>
			Five standalone HTML pages with shared navigation. No framework, no build step, no server:
			each page carries its own data and logic, so the whole set opens from a folder.
		</li>
		<li>
			The 83 shipments are embedded from the shipping export: ID, door, destination, product family,
			pallet count, weight, declared volume, operator-keyed fill and notes.
		</li>
		<li>
			The pages follow the site theme: light by default, dark when the visitor has chosen it. The 3D
			scenes read their colours from the same CSS variables.
		</li>
	</ul>

	<h3>The loading model</h3>
	<dl>
		<div>
			<dt>Container</dt>
			<dd>40 ft high-cube, 12.03 × 2.35 × 2.69 m, 67 m³, 26,000 kg</dd>
		</div>
		<div>
			<dt>Layout</dt>
			<dd>10 rows × 2 floor positions, pallet footprint 1.2 × 1.0 m</dd>
		</div>
		<div>
			<dt>Stack limit</dt>
			<dd>2.62 m (interior height less an assumed 7 cm clearance)</dd>
		</div>
		<div>
			<dt>Reach</dt>
			<dd>The crew can pull any of the next 8 pallets forward</dd>
		</div>
	</dl>
	<p>
		Each pallet takes the left floor spot, then the right, then stacks on whichever floor pallet it
		fits on without passing the limit. If neither stack position fits, the row closes and the unused
		positions are counted as lost. When rows run out, the pallet is left at the dock.
	</p>

	<h3>Where the heights come from</h3>
	<p>
		Nobody has measured pallet height, so heights are generated per product family from a mean and
		spread, drawn with a seeded random generator and clamped to 0.6–1.55 m. The same shipment always
		produces the same pallets, so every result is repeatable. Brake rotors and cast housings are
		floor-only, following the brief's scoping answer that nothing goes on top of them.
	</p>

	<h3>The recommendation engine</h3>
	<ol>
		<li>After every pallet, replay the remaining plan to a finished container.</li>
		<li>
			Try each pallet within reach as the next one, replay again, and keep the best result: most
			pallets shipped, then fewest lost positions.
		</li>
		<li>
			Check the last moment: if loading the planned pallet first would still allow the same fix,
			stay quiet. Only when waiting one more pallet would lose it does the pallet become a Hold.
		</li>
		<li>
			Withhold the recommendation if the pallet's identity is unverified. Log, without interrupting,
			a change that only saves a stack position.
		</li>
		<li>
			Escalate only when a pallet is still projected to roll and nothing within reach fixes it.
		</li>
	</ol>
	<p>
		A full re-plan takes about a millisecond in the browser, so the live view recomputes after every
		pallet.
	</p>

	<h3>Planned versus Platform sequence</h3>
	<p>
		The Planned view replays the original load plan into an empty container. The Platform view
		clones the live session and runs it forward with the recommendations applied. Both use the same
		loader, so the difference on screen is the sequence and nothing else.
	</p>

	<h3>Across the fleet</h3>
	<p>
		The fleet table runs all 83 containers through the same loader and engine on page load, then
		sorts each into fits, fixable by one swap, or stuck. Fleet live and Enterprise each have a
		picker over all 83 loads, so any of them can be stepped through.
	</p>

	<h3>Rendering</h3>
	<p>
		The scenes are drawn on a 2D canvas with a small isometric projection: three cameras (3D, door,
		top-down), boxes depth-sorted and shaded per face, and click targets found by testing the
		projected faces. There is no WebGL and no library.
	</p>

	<h3>Honesty is part of the interface</h3>
	<ul>
		<li>Every fact is tagged real, specification, inferred or simulated.</li>
		<li>A banner on every page says what is real and what is simulated.</li>
		<li>
			Outcomes carry a standing counterfactual note: the real export records the load as complete.
		</li>
		<li>No alert or message is ever sent; escalations are logged as simulated.</li>
	</ul>

	<h3>How I checked it</h3>
	<p>
		I ran full simulations in a real browser through scripted clicks, scanned every page at six
		widths from 375 to 1920 px for overflow and clipped text, and ran a contrast check in both
		themes. There is no committed test suite. A pilot would need one around the loader first.
	</p>

	<h3>What is not built</h3>
	<ul>
		<li>No vision model, camera integration or pallet detection.</li>
		<li>No connection to the shipping system's load plan.</li>
		<li>
			The 85% confidence bar and the reach window of 8 are placeholders to tune against real data.
		</li>
	</ul>
	<p>
		Swapping in real inputs is a data change: measured heights and readings in place of the
		generated ones, and the actual load plan in place of the export order.
	</p>
</SlideOver>

